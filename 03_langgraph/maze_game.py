# Player position
player_x, player_y = 1, 1  # Starting position

# Goal position
goal_x, goal_y = 28, 29 # maze[29][28] is a path. Let's use that as goal.

# Game loop
running = True
game_over = False

while running:
    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False
        if event.type == pygame.KEYDOWN and not game_over:
            new_player_x, new_player_y = player_x, player_y
            if event.key == pygame.K_LEFT:
                new_player_x -= 1
            if event.key == pygame.K_RIGHT:
                new_player_x += 1
            if event.key == pygame.K_UP:
                new_player_y -= 1
            if event.key == pygame.K_DOWN:
                new_player_y += 1

            # Check for wall collision
            if 0 <= new_player_x < MAZE_WIDTH and \
               0 <= new_player_y < MAZE_HEIGHT and \
               maze[new_player_y][new_player_x] == 1:
                player_x, player_y = new_player_x, new_player_y

            # Check for win condition
            if player_x == goal_x and player_y == goal_y:
                game_over = True

    # Drawing
    screen.fill(BLACK)

    for y in range(MAZE_HEIGHT):
        for x in range(MAZE_WIDTH):
            if maze[y][x] == 0:  # Wall
                pygame.draw.rect(screen, BLUE, (x * CELL_SIZE, y * CELL_SIZE, CELL_SIZE, CELL_SIZE))
            elif maze[y][x] == 1: # Path
                 pygame.draw.rect(screen, WHITE, (x * CELL_SIZE, y * CELL_SIZE, CELL_SIZE, CELL_SIZE), 1) # Draw path outlines

    # Draw player
    pygame.draw.rect(screen, RED, (player_x * CELL_SIZE, player_y * CELL_SIZE, CELL_SIZE, CELL_SIZE))

    # Draw goal
    pygame.draw.rect(screen, GREEN, (goal_x * CELL_SIZE, goal_y * CELL_SIZE, CELL_SIZE, CELL_SIZE))

    if game_over:
        font = pygame.font.Font(None, 74)
        text = font.render("You Win!", True, GREEN)
        text_rect = text.get_rect(center=(SCREEN_WIDTH // 2, SCREEN_HEIGHT // 2))
        screen.blit(text, text_rect)

    pygame.display.flip()

# Quit Pygame
